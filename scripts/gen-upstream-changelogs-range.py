"""Generate docs/changelogs/{whisper-cpp,ggml}-OLD-to-NEW.md for an explicit whisper.cpp revision range.

Sibling of gen-upstream-changelogs.py (whose helpers it reuses): instead of deriving the
whisper.cpp revisions from Cargo.lock, both are given on the command line. The matching ggml
revisions are read from `scripts/sync-ggml.last` at those two whisper.cpp revisions. Everything
written is either verbatim upstream data (GitHub release bodies, git subjects) or a fixed-format
rendering of `git log`.

Usage: uv run scripts/gen-upstream-changelogs-range.py [--old v1.8.3] [--new v1.9.5] [--work-dir DIR]
"""

import argparse
import importlib.util
import os
from datetime import UTC, datetime
from pathlib import Path
from types import ModuleType


def load_base() -> ModuleType:
    path = Path(__file__).resolve().with_name("gen-upstream-changelogs.py")
    spec = importlib.util.spec_from_file_location("gen_upstream_changelogs", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


base = load_base()


def resolve(repo: Path, rev: str) -> str:
    return base.git(repo, "rev-parse", f"{rev}^{{commit}}").strip()


def cmake_line(repo: Path, rev: str) -> str:
    prefixes = (
        'project("whisper.cpp" VERSION',
        "set(WHISPER_VERSION_MAJOR",
        "set(WHISPER_VERSION_MINOR",
        "set(WHISPER_VERSION_PATCH",
    )
    text = base.git(repo, "show", f"{rev}:CMakeLists.txt")
    return "; ".join(f"`{line.strip()}`" for line in text.splitlines() if line.startswith(prefixes))


def ggml_version_lines(repo: Path, rev: str) -> str:
    text = base.git(repo, "show", f"{rev}:ggml/CMakeLists.txt")
    found = "; ".join(
        f"`{line.strip()}`" for line in text.splitlines() if line.startswith("set(GGML_VERSION_") and "BASE" not in line
    )
    return found or "(no GGML_VERSION_* lines)"


def day(repo: Path, rev: str) -> str:
    return base.zurich(int(base.git(repo, "log", "-1", "--format=%ct", rev).strip())).date().isoformat()


def build_whisper_cpp(repo: Path, old: str, new: str, old_name: str, new_name: str, generated: str) -> str:
    rng = f"{old}..{new}"
    tags = base.range_tags(repo, old, new)
    releases = base.github_releases(base.WHISPER_CPP)
    url_base = f"https://github.com/{base.WHISPER_CPP}/commit"
    entries = base.commits(repo, rng)
    lines = [
        f"# whisper.cpp changes, {old_name} to {new_name}",
        "",
        "Generated by `scripts/gen-upstream-changelogs-range.py`; do not edit by hand.",
        "",
        f"- Generated: {generated}",
        f"- Source repository: https://github.com/{base.WHISPER_CPP} (git history and GitHub Releases API)",
        f"- Old whisper.cpp revision: `{old}` (`{old_name}`), given on the command line; CMakeLists: {cmake_line(repo, old)}",
        f"- New whisper.cpp revision: `{new}` (`{new_name}`), given on the command line; CMakeLists: {cmake_line(repo, new)}",
        f"- Commit range: `{rng}`, merges excluded ({len(entries)} commits)",
        f"- Release notes: GitHub Releases bodies of the version tags contained in the range ({base.tag_names(tags)}), verbatim.",
        "- Commit subjects are verbatim; dates are Europe/Zurich days. Commits are grouped by the tag segment they fall in.",
        "",
    ]
    lines += base.render_releases(tags, releases)
    lines += ["# Commits", ""]
    segments: list[tuple[str, list]] = []
    previous = old
    for tag in tags:
        segments.append((f"{previous[:10]}..{tag.name}", base.commits(repo, f"{previous}..{tag.commit}")))
        previous = tag.commit
    trailing = base.commits(repo, f"{previous}..{new}")
    if trailing:
        segments.append((f"{previous[:10]}..{new[:10]} (after the last tag)", trailing))
    for title, segment in reversed(segments):
        lines += [f"## {title}: {len(segment)} commits", ""]
        lines += base.render_commits(segment, url_base, "###")
    name = f"whisper-cpp-{old_name.removeprefix('v')}-to-{new_name.removeprefix('v')}.md"
    base.write(name, lines)
    return name


def build_ggml(
    wcpp_repo: Path, repo: Path, wcpp: tuple[str, str], pins: tuple[str, str], names: tuple[str, str], generated: str
) -> str:
    (old_wcpp, new_wcpp), (old, new), (old_name, new_name) = wcpp, pins, names
    rng = f"{old}..{new}"
    tags = base.range_tags(repo, old, new)
    releases = base.github_releases(base.GGML)
    url_base = f"https://github.com/{base.GGML}/commit"
    entries = base.commits(repo, rng)
    after_last_tag = len(base.commits(repo, f"{tags[-1].commit}..{new}")) if tags else len(entries)
    lines = [
        f"# ggml changes, as vendored by whisper.cpp {old_name} to {new_name}",
        "",
        "Generated by `scripts/gen-upstream-changelogs-range.py`; do not edit by hand.",
        "",
        f"- Generated: {generated}",
        (
            f"- Source repository: https://github.com/{base.GGML} (git history and GitHub Releases API). "
            "This is the upstream repository that whisper.cpp vendors under `ggml/`; the ggml history inside whisper.cpp is not used."
        ),
        f"- Old ggml revision: `{old}` ({day(repo, old)}), the content of `scripts/sync-ggml.last` at whisper.cpp `{old_wcpp}` (`{old_name}`)",
        f"- New ggml revision: `{new}` ({day(repo, new)}), the content of `scripts/sync-ggml.last` at whisper.cpp `{new_wcpp}` (`{new_name}`)",
        (
            f"- `ggml/CMakeLists.txt` version lines at the old whisper.cpp revision: {ggml_version_lines(wcpp_repo, old_wcpp)}; "
            f"at the new one: {ggml_version_lines(wcpp_repo, new_wcpp)}"
        ),
        f"- Commit range: `{rng}`, merges excluded ({len(entries)} commits)",
        (
            f"- Release notes: GitHub Releases bodies of the version tags contained in the range ({base.tag_names(tags)}), verbatim. "
            f"{after_last_tag} commits come after the last tag of the range and are covered by no release."
        ),
        "- Commit subjects are verbatim; commits are grouped by Europe/Zurich day.",
        "",
    ]
    lines += base.render_releases(tags, releases)
    lines += [f"# Commits: {len(entries)}", ""]
    lines += base.render_commits(entries, url_base, "##")
    name = f"ggml-{old_name.removeprefix('v')}-to-{new_name.removeprefix('v')}.md"
    base.write(name, lines)
    return name


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--old", default="v1.8.3", help="old whisper.cpp tag or commit")
    parser.add_argument("--new", default="v1.9.5", help="new whisper.cpp tag or commit")
    parser.add_argument("--work-dir", type=Path, default=Path(os.environ.get("TEMP", "/tmp")) / "purr-upstream-changelogs")
    args = parser.parse_args()

    generated = f"{base.zurich(datetime.now(UTC).timestamp()):%Y-%m-%d %H:%M} (Europe/Zurich)"
    args.work_dir.mkdir(parents=True, exist_ok=True)
    wcpp_repo = base.ensure_clone(f"https://github.com/{base.WHISPER_CPP}.git", args.work_dir / "whisper.cpp")
    ggml_repo = base.ensure_clone(f"https://github.com/{base.GGML}.git", args.work_dir / "ggml")

    old, new = resolve(wcpp_repo, args.old), resolve(wcpp_repo, args.new)
    old_ggml = base.git(wcpp_repo, "show", f"{old}:scripts/sync-ggml.last").strip()
    new_ggml = base.git(wcpp_repo, "show", f"{new}:scripts/sync-ggml.last").strip()

    build_whisper_cpp(wcpp_repo, old, new, args.old, args.new, generated)
    build_ggml(wcpp_repo, ggml_repo, (old, new), (old_ggml, new_ggml), (args.old, args.new), generated)


if __name__ == "__main__":
    main()
